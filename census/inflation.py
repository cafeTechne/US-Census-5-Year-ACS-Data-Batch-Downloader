"""Inflation adjustment and longitudinal comparability advisories.

ACS 5-year dollar values are expressed in dollars of the period's final year
(the 2018-2022 ACS reports 2022 dollars). To compare across periods, convert to
a common base year:

    real_base = nominal_t * INDEX_base / INDEX_t

The Census Bureau adjusts ACS dollar values with the R-CPI-U-RS (all items),
so that is the default index. CPI-U is available for comparison. Index values
live in data/price_indexes/*.csv, generated by scripts/update_price_indexes.py
from BLS sources and checksummed in sidecar JSON files; nothing is hand-typed.
"""

import csv
import json
import os
import re
from functools import lru_cache
from typing import Any, Dict, Iterable, List, Mapping, Optional

import pandas as pd

from census.geo import get_resource_path
from census.stats import parse_variable_code

R_CPI_U_RS = "r-cpi-u-rs"
CPI_U = "cpi-u"
PRICE_INDEXES = (R_CPI_U_RS, CPI_U)
DEFAULT_PRICE_INDEX = R_CPI_U_RS
_INDEX_FILES = {R_CPI_U_RS: "r_cpi_u_rs", CPI_U: "cpi_u"}
INDEX_DISPLAY = {R_CPI_U_RS: "R-CPI-U-RS", CPI_U: "CPI-U"}


class PriceIndexUnavailable(KeyError):
    """Raised when an index (or a year of it) is not available locally."""


def price_index_dir() -> str:
    return os.getenv("CENSUS_PRICE_INDEX_DIR") or get_resource_path(
        os.path.join("data", "price_indexes")
    )


@lru_cache(maxsize=None)
def load_price_index(index: str = DEFAULT_PRICE_INDEX) -> Dict[int, float]:
    """Annual index values by year; empty dict if the data file is missing."""
    if index not in _INDEX_FILES:
        raise ValueError(f"Unknown price index '{index}'. Choose from {PRICE_INDEXES}.")
    path = os.path.join(price_index_dir(), f"{_INDEX_FILES[index]}.csv")
    if not os.path.exists(path):
        return {}
    with open(path, newline="", encoding="utf-8") as f:
        return {int(r["year"]): float(r["value"]) for r in csv.DictReader(f)}


@lru_cache(maxsize=None)
def price_index_info(index: str = DEFAULT_PRICE_INDEX) -> Dict[str, Any]:
    """Source metadata (sidecar JSON) for an index, or {} when missing."""
    path = os.path.join(price_index_dir(), f"{_INDEX_FILES[index]}.json")
    if not os.path.exists(path):
        return {}
    with open(path, encoding="utf-8") as f:
        return json.load(f)


# Backward-compatible name for the CPI-U table (now file-backed).
CPI_U_ANNUAL: Dict[int, float] = load_price_index(CPI_U)
CPI_SOURCE = "BLS CPI-U, U.S. city average, all items, annual average (CUUR0000SA0)"

_DOLLAR_RE = re.compile(r"\bdollars\b", re.IGNORECASE)

# ACS 5-year datasets: tract and other small-area geographies were redrawn for
# the 2020 Census and first appear in the 2020 (2016-2020) ACS 5-year release.
BOUNDARY_VINTAGE_BREAK = 2020
BOUNDARY_SENSITIVE_LEVELS = {"tract", "zcta", "place", "county", "msa"}

# ACS user note 2023-07: home values are presented in current-year dollars
# starting with the 2022 releases. Earlier releases' home values were not on
# the period end-year basis, so deflating them by end-year index is approximate.
HOME_VALUE_DOLLAR_BASIS_CHANGE = 2022
HOME_VALUE_TABLE_PREFIXES = (
    "B25075", "B25076", "B25077", "B25078", "B25079", "B25080", "B25081",
    "B25082", "B25083", "B25085", "B25096", "B25097", "B25100", "B25107",
    "B25108", "B25109", "B25110", "B25121", "CP04", "DP04",
)
HOME_VALUE_NOTE_URL = (
    "https://www.census.gov/programs-surveys/acs/technical-documentation/user-notes/2023-07.html"
)


def _resolve_table(index: str, cpi_table: Optional[Mapping[int, float]]) -> Mapping[int, float]:
    if cpi_table is not None:
        return cpi_table
    table = load_price_index(index)
    if not table:
        raise PriceIndexUnavailable(
            f"No {INDEX_DISPLAY.get(index, index)} data in {price_index_dir()}. "
            "Run scripts/update_price_indexes.py (see its docstring), or pass cpi_table=."
        )
    return table


def get_cpi(
    year: int,
    cpi_table: Optional[Mapping[int, float]] = None,
    index: str = DEFAULT_PRICE_INDEX,
) -> float:
    table = _resolve_table(index, cpi_table)
    if year not in table:
        raise PriceIndexUnavailable(
            f"No {INDEX_DISPLAY.get(index, 'index')} value for {year}. Available years: "
            f"{min(table)}-{max(table)}. Run scripts/update_price_indexes.py or pass cpi_table=."
        )
    return float(table[year])


def inflation_factor(
    from_year: int,
    to_year: int,
    cpi_table: Optional[Mapping[int, float]] = None,
    index: str = DEFAULT_PRICE_INDEX,
) -> float:
    """Multiplier converting from_year dollars into to_year dollars."""
    return get_cpi(to_year, cpi_table, index) / get_cpi(from_year, cpi_table, index)


def adjust_inflation(
    value: float,
    from_year: int,
    to_year: int,
    cpi_table: Optional[Mapping[int, float]] = None,
    index: str = DEFAULT_PRICE_INDEX,
) -> float:
    """Convert a nominal dollar value from from_year dollars to to_year dollars."""
    return float(value) * inflation_factor(from_year, to_year, cpi_table, index)


def home_value_advisory(table_code: str, years: Iterable[int]) -> Optional[str]:
    """Advisory for deflating home-value tables from releases before 2022."""
    early = sorted(y for y in years if y < HOME_VALUE_DOLLAR_BASIS_CHANGE)
    if not early or not table_code.upper().startswith(HOME_VALUE_TABLE_PREFIXES):
        return None
    return (
        f"HOME VALUE ADVISORY: {table_code} home values in releases before "
        f"{HOME_VALUE_DOLLAR_BASIS_CHANGE} ({early[0]}-{early[-1]}) were not presented in "
        "period end-year dollars, so end-year inflation adjustment of those values is "
        f"approximate. Source: {HOME_VALUE_NOTE_URL}"
    )


def is_dollar_variable(label: str, concept: str = "") -> bool:
    """True when a variable's *value* is a dollar amount (not a count in a $ bracket).

    Census labels put dollar context in parent headings and concepts, e.g.
    "INCOME AND BENEFITS (IN 2022 INFLATION-ADJUSTED DOLLARS)!!Total
    households!!Less than $10,000" is a household count. So only the leaf
    label decides, plus tables whose concept is itself a dollar statistic
    (MEDIAN GROSS RENT (DOLLARS), MEDIAN HOUSEHOLD INCOME ... BY AGE).
    """
    if not label:
        return False
    leaf = label.split("!!")[-1].strip()
    if "$" in leaf or re.search(r"percent|rate\b|ratio", leaf, re.IGNORECASE):
        return False
    if _DOLLAR_RE.search(leaf):  # "(dollars)", "(in 2021 inflation-adjusted dollars)"
        return True
    stat = re.compile(r"^(median|mean|aggregate|average|per capita)\b", re.IGNORECASE)
    if stat.match(leaf) and _DOLLAR_RE.search(f"{label} {concept}"):
        return True
    concept = concept.strip()
    return bool(stat.match(concept) and _DOLLAR_RE.search(concept))


def dollar_columns(
    columns: Iterable[str], metadata: Mapping[str, Mapping[str, str]]
) -> List[str]:
    """Estimate/MOE columns (E, M) whose variable is dollar-denominated.

    ``metadata`` maps variable codes to {"label", "concept"}. The estimate's
    metadata decides for its MOE too. Percent columns are never selected.
    """
    selected: List[str] = []
    for col in columns:
        parsed = parse_variable_code(str(col))
        if not parsed or parsed[1] not in ("E", "M"):
            continue
        entry = metadata.get(f"{parsed[0]}E") or {}
        if is_dollar_variable(str(entry.get("label", "")), str(entry.get("concept", ""))):
            selected.append(col)
    return selected


def deflate_dataframe(
    df: pd.DataFrame,
    year: int,
    base_year: int,
    columns: Iterable[str],
    cpi_table: Optional[Mapping[int, float]] = None,
    index: str = DEFAULT_PRICE_INDEX,
) -> pd.DataFrame:
    """Scale the given dollar columns from ``year`` dollars into ``base_year`` dollars.

    MOEs scale by the same factor, so they should be included in ``columns``.
    """
    out = df.copy()
    factor = inflation_factor(year, base_year, cpi_table, index)
    for col in columns:
        if col in out.columns:
            out[col] = pd.to_numeric(out[col], errors="coerce") * factor
    return out


def boundary_shift_advisory(
    start_year: int, end_year: int, geo_level: str = ""
) -> Optional[str]:
    """Warn when a multi-year request spans the 2010 -> 2020 boundary vintages."""
    if not (start_year < BOUNDARY_VINTAGE_BREAK <= end_year):
        return None
    if geo_level and geo_level not in BOUNDARY_SENSITIVE_LEVELS:
        return None  # state / national boundaries are stable
    detail = {
        "tract": "Many census tracts were split, merged, or renumbered; tract GEOIDs "
        "before and after 2020 do not describe the same areas. Use a crosswalk "
        "(e.g. Census tract relationship files or NHGIS/LTDB) before panel analysis.",
        "zcta": "ZCTAs were re-delineated from 2020 Census address data; some ZCTAs "
        "were added, dropped, or changed shape.",
        "place": "Place boundaries are updated annually and were re-delineated for "
        "2020 (notably CDPs); compare with caution.",
        "county": "A few counties changed (e.g. Connecticut planning regions from "
        "2022; Alaska boroughs); most counties are stable.",
        "msa": "CBSA delineations changed (OMB 2013, 2018, 2020, 2023 bulletins); "
        "metro definitions may differ across years.",
    }.get(geo_level, "")
    msg = (
        f"BOUNDARY ADVISORY: The requested years {start_year}-{end_year} span the "
        f"2019/2020 ACS 5-year boundary vintage change (2010 Census geography -> "
        f"2020 Census geography)."
    )
    return f"{msg} {detail}".strip()
